const page = (
  typeId: string,
  name: string,
  folder: string,
  typeName: string,
  fields: PageField[],
): PageSpec => ({
  typeId,
  name,
  description: `Texts of the ${name.replace(/ page$/, '')} page.`,
  output: {
    file: `src/pages/${folder}/model/page.generated.ts`,
    exportName: 'PAGE_TEXT',
    typeName,
    typeFrom: './content',
  },
  fields,
});

